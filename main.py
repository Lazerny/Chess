import chess

# Создание доски
board = chess.Board()

# Перевод доски в позицию с патом для белых (для примера)
board.set_fen("8/8/8/8/8/2k5/8/4K3 b - - 0 1")  # Белый король на e1, черный король на d7, черные ходят

# Проверка на пат
if board.is_stalemate():
    print("Доска в пате!")
else:
    print("Доска не в пате.")